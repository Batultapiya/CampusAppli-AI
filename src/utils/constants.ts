export function getSmartSubject(reason: string, customReason?: string): string {
  if (reason === 'Other' && customReason) {
    const clean = customReason.trim();
    if (clean.toLowerCase().startsWith('request for') || clean.toLowerCase().startsWith('application for')) {
      return clean;
    }
    return `Application Request regarding ${clean}`;
  }
  return SMART_SUBJECT_MAP[reason] || `Application Request for ${reason}`;
}

